import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = f => readFileSync(f, 'utf8');
const base = 'ops/windows/oh6cr3/';
const supervisor = read(base + 'HostSupervisor.ps1');
const status = read(base + 'HostStatus.ps1');
const kick = read(base + 'HostLoginKickstart.ps1');
const enable = read(base + 'Enable-LoginFallback.ps1');
const disable = read(base + 'Disable-LoginFallback.ps1');
const all = [supervisor,status,kick,enable,disable].join('\n');
const pass=(msg, ok) => { assert.ok(ok, msg); console.log('PASS ' + msg); };
pass('Two-cycle down hold', /ConsecutiveNextDown -ge 2/.test(supervisor));
pass('Next process ownership check before launching', /Test-NextRepositoryProcess/.test(supervisor) && /IndexOf\(\$Repo/.test(supervisor));
pass('Last-second port and process re-check', /Start-Sleep -Seconds 3/.test(supervisor) && /-not \(Test-Listen 3000\)/.test(supervisor));
pass('240 second cooldown and no process killing', /TotalSeconds -ge 240/.test(supervisor) && !/Stop-Process|taskkill/i.test(supervisor));
pass('Stale status does not imply active supervision', /taskRunning -and \$fresh/.test(status) && /snapshot age/i.test(status));
pass('Kickstart never launches the application directly', /Start-ScheduledTask/.test(kick) && /\$task.State -eq 'Running'/.test(kick) && !/Start-Process|node.exe|ollama.exe/i.test(kick));
pass('Explicit opt-in link with existing conflict protection', /CreateShortcut/.test(enable) && /Refusing to overwrite/.test(enable) && /\[switch\]\$StartNow/.test(enable));
pass('Owner removal validates link target first', /HostLoginKickstart/.test(disable) && /Remove-Item/.test(disable));
pass('No system-level operations', !/Register-ScheduledTask|Unregister-ScheduledTask|Set-Service|Restart-Service|schtasks \/create|tailscale up/i.test(all));
console.log('OH-6J1J2 HOST HARDENING: PASS (static verification only)');
