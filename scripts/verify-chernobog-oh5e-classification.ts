import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { OH5WorkingMemory, classifyRawEvidence } from "../packages/vault/src/oh5/classification";
import { OH5ObsidianLayout } from "../packages/vault/src/oh5/layout";
import { GovernedMemoryStore } from "../packages/vault/src/oh5/store";
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),"chernobog-oh5e-"));
const vault=path.join(tmp,"vault");fs.mkdirSync(path.join(vault,".obsidian"),{recursive:true});
const db=path.join(tmp,"memory.sqlite");
const layout=new OH5ObsidianLayout(vault);layout.registerProject("malware","Malware",true);layout.registerProject("vestige","Vestige",true);
const governed=new GovernedMemoryStore(db);
let working=new OH5WorkingMemory(db,vault);let count=0;
const check=(name:string,test:()=>void)=>{test();console.log("PASS",name);count++;};
try {
 check("decision requires review",()=>assert.equal(classifyRawEvidence("We decided the plan").needsOwnerReview,true));
 check("task classified as candidate",()=>assert.equal(classifyRawEvidence("Need to finish the task").handling,"candidate"));
 check("project progress classified",()=>assert.equal(classifyRawEvidence("Milestone completed").category,"project-update"));
 check("preference classified",()=>assert.equal(classifyRawEvidence("I prefer this route").category,"preference"));
 check("small talk ignored",()=>assert.equal(classifyRawEvidence("thanks").handling,"ignore"));
 check("uncertain retained temporarily",()=>assert.equal(classifyRawEvidence("Some observation").handling,"temporary"));
 check("empty text rejected",()=>assert.throws(()=>classifyRawEvidence("  ")));
 const raw=governed.ingest({projectId:"malware",body:"We decided to retain this draft",channel:"discord",sourceRef:"discord:abc"});
 const a=working.triage("malware",raw.id);
 check("raw stays raw",()=>assert.equal(governed.get("malware",raw.id)?.tier,"raw"));
 check("candidate scratchpad created",()=>assert.equal(a.item?.handling,"candidate"));
 check("owner review required",()=>assert.equal(a.classification.needsOwnerReview,true));
 check("other project cannot triage record",()=>assert.throws(()=>working.triage("vestige",raw.id)));
 check("unregistered project rejected",()=>assert.throws(()=>working.list("nonexistent")));
 check("traversal rejected",()=>assert.throws(()=>working.list("../malware")));
 check("cross project list isolated",()=>assert.equal(working.list("vestige").length,0));
 check("triage idempotent",()=>assert.equal(working.triage("malware",raw.id).item?.id,a.item?.id));
 check("confirmed recall excludes raw",()=>assert.equal(governed.recall("malware","decided").length,0));
 const other=governed.ingest({projectId:"malware",body:"Odd observation",channel:"file",sourceRef:"file:x"});
 working.triage("malware",other.id);
 check("temporary cannot promote",()=>assert.throws(()=>working.proposeForReview("malware",other.id,1)));
 check("candidate stale revision blocked",()=>assert.throws(()=>working.proposeForReview("malware",raw.id,99)));
 const candidate=working.proposeForReview("malware",raw.id,1);
 check("explicit candidate proposal works",()=>assert.equal(candidate.tier,"candidate"));
 check("proposal never confirms",()=>assert.notEqual(candidate.tier,"confirmed"));
 check("repeat proposal blocked",()=>assert.throws(()=>working.proposeForReview("malware",raw.id,2)));
 check("candidate excluded from confirmed recall",()=>assert.equal(governed.recall("malware","decided").length,0));
 check("expired records excluded from listing",()=>assert.equal(working.list("malware",new Date(Date.now()+8*86400000)).length,0));
 check("invalid TTL rejected",()=>assert.throws(()=>working.triage("malware",other.id,{ttlMs:1})));
 working.close();working=new OH5WorkingMemory(db,vault);
 check("scratchpad survives restart",()=>assert.equal(working.list("malware").length,2));
 check("purge expired works",()=>assert.equal(working.purgeExpired(new Date(Date.now()+8*86400000)),2));
 check("purge does not delete raw evidence",()=>assert.ok(governed.get("malware",other.id)));
 console.log(`OH-5E CLASSIFICATION AND WORKING MEMORY: PASS ${count}/${count}`);
} finally {working.close();governed.close();fs.rmSync(tmp,{recursive:true,force:true});}