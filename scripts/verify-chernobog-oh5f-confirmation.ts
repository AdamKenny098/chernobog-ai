import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import {OH5ObsidianLayout} from "../packages/vault/src/oh5/layout";
import {GovernedMemoryStore} from "../packages/vault/src/oh5/store";
import {OH5ConfirmationGate} from "../packages/vault/src/oh5/confirmation";
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),"oh5f-"));
const root=path.join(tmp,"vault");fs.mkdirSync(path.join(root,".obsidian"),{recursive:true});
const db=path.join(tmp,"memory.sqlite");
const layout=new OH5ObsidianLayout(root);layout.registerProject("malware","Malware",true);layout.registerProject("vestige","Vestige",true);
const memory=new GovernedMemoryStore(db);const gate=new OH5ConfirmationGate(db,root);let count=0;
function check(label:string,run:()=>void){run();count++;console.log("PASS "+label);}
try{
 const raw=memory.ingest({projectId:"malware",body:"We decided the project architecture",sourceRef:"conversation:test",channel:"owner-ui"});
 const candidate=memory.propose({projectId:"malware",id:raw.id,expectedRevision:raw.revision,channel:"model"});
 check("candidate present in owner queue",()=>assert.equal(gate.queue("malware").length,1));
 check("second project cannot see candidate",()=>assert.equal(gate.queue("vestige").length,0));
 check("preview requires authenticated owner",()=>assert.throws(()=>gate.preview("malware",candidate.id,false)));
 check("wrong project cannot preview",()=>assert.throws(()=>gate.preview("vestige",candidate.id,true)));
 const review=gate.preview("malware",candidate.id,true);
 check("preview shows exact candidate",()=>assert.equal(review.body,candidate.body));
 check("preview retains source",()=>assert.equal(review.sourceRef,candidate.sourceRef));
 const action={projectId:"malware",memoryId:candidate.id,nonce:review.nonce,fingerprint:review.fingerprint,action:"confirm" as const,reason:"Owner reviewed the exact claim",acknowledgement:"lock it in"};
 check("missing owner authentication blocked",()=>assert.throws(()=>gate.decide(action,false)));
 check("phrase mismatch blocked",()=>assert.throws(()=>gate.decide({...action,acknowledgement:"yes"},true)));
 check("incorrect fingerprint blocked",()=>assert.throws(()=>gate.decide({...action,fingerprint:"0".repeat(64)},true)));
 check("wrong project blocked",()=>assert.throws(()=>gate.decide({...action,projectId:"vestige"},true)));
 check("empty rationale blocked",()=>assert.throws(()=>gate.decide({...action,reason:" "},true)));
 check("candidate unconfirmed until owner action",()=>assert.equal(memory.get("malware",candidate.id)?.tier,"candidate"));
 const confirmed=gate.decide(action,true);
 check("explicit owner decision confirms",()=>assert.equal(confirmed.tier,"confirmed"));
 check("exact memory wording preserved",()=>assert.equal(confirmed.body,candidate.body));
 check("approval cannot replay",()=>assert.throws(()=>gate.decide(action,true)));
 check("approval audit preserved",()=>assert.ok(memory.audit("malware",candidate.id).some((e:unknown)=>(e as {action:string}).action==="confirm")));
 check("project-isolated recall",()=>assert.equal(memory.recall("vestige","architecture").length,0));
 check("confirmed visible in own project",()=>assert.equal(memory.recall("malware","architecture").length,1));
 const raw2=memory.ingest({projectId:"malware",body:"A later candidate",sourceRef:"conversation:test2",channel:"owner-ui"});
 const can2=memory.propose({projectId:"malware",id:raw2.id,expectedRevision:1,channel:"model"});
 const rev2=gate.preview("malware",can2.id,true);
 check("rejection needs explicit phrase",()=>assert.throws(()=>gate.decide({projectId:"malware",memoryId:can2.id,nonce:rev2.nonce,fingerprint:rev2.fingerprint,action:"reject",reason:"Incorrect",acknowledgement:"lock it in"},true)));
 const rejected=gate.decide({projectId:"malware",memoryId:can2.id,nonce:rev2.nonce,fingerprint:rev2.fingerprint,action:"reject",reason:"Incorrect",acknowledgement:"reject"},true);
 check("owner rejection applied",()=>assert.equal(rejected.tier,"rejected"));
 gate.close();
 const reopened=new OH5ConfirmationGate(db,root);
 check("review queue durable across restart",()=>assert.equal(reopened.queue("malware").length,0));
 reopened.close();
 console.log(`OH-5F OWNER CONFIRMATION: PASS ${count}/${count}`);
}finally{memory.close();fs.rmSync(tmp,{recursive:true,force:true});}